import { expect, test } from '@playwright/test'

test('lista lotes compactos em páginas de dez registros e preserva os detalhes ao navegar', async ({ page, isMobile }, testInfo) => {
  await page.addInitScript(() => {
    const prefix = 'fluxo-publico:tenant:prefeitura-saomateus-ma:'
    localStorage.setItem(`${prefix}user`, 'usr-clara')
    localStorage.setItem(`${prefix}unit`, 'u-prot')
    localStorage.setItem(`${prefix}theme`, 'dark')
  })
  await page.goto('/lotes')
  const pagination = page.getByRole('navigation', { name: 'Paginação de lotes', exact: true })
  await expect(pagination).toContainText('0 registros')
  await expect(pagination.getByRole('button', { name: 'Anterior', exact: true })).toBeDisabled()
  await expect(pagination.getByRole('button', { name: 'Próxima', exact: true })).toBeDisabled()
  await page.evaluate(() => {
    const key = 'fluxo-publico:tenant:prefeitura-saomateus-ma:database:v1'
    const db = JSON.parse(localStorage.getItem(key)!)
    const protocol = db.protocols.find((item: { id: string }) => item.id === 'pr-1')
    db.batches = Array.from({ length: 23 }, (_, index) => ({ id: `pagination-batch-${index + 1}`, number: `2026.${String(index + 1).padStart(6, '0')}`, actorUserId: 'usr-clara', actorName: 'Clara Nunes', actorUnitId: 'u-prot', createdAt: new Date(Date.UTC(2026, 9, 16, 12, index)).toISOString(), typeIds: [protocol.typeId], phaseId: 'phase-analysis', phaseName: 'Análise técnica dos documentos apresentados', unitId: 'u-adm', unitName: 'Secretaria Municipal de Administração e Planejamento', message: `Encaminhamento do lote ${index + 1}.`, protocols: [{ protocolId: protocol.id, number: protocol.number, typeId: protocol.typeId, eventId: `event-${index}`, expectedVersion: 1 }] }))
    localStorage.setItem(key, JSON.stringify(db))
  })
  await page.reload()
  const history = page.getByRole('region', { name: 'Histórico de lotes', exact: true })
  const rows = history.locator('article')
  await expect(rows).toHaveCount(10)
  await expect(pagination).toContainText('23 registros')
  await expect(pagination).toContainText('1 / 3')
  await expect(rows.first().getByRole('heading', { name: 'Lote 2026.000023', exact: true })).toBeVisible()
  expect((await rows.first().boundingBox())!.height).toBeLessThanOrEqual(isMobile ? 112 : 76)
  expect(await rows.first().evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('compact-batches.png') })
  await pagination.getByRole('button', { name: 'Próxima', exact: true }).click()
  await expect(pagination).toContainText('2 / 3')
  await expect(rows).toHaveCount(10)
  await expect(rows.first().getByRole('heading', { name: 'Lote 2026.000013', exact: true })).toBeAttached()
  await rows.first().getByRole('button', { name: 'Ver lote', exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Lote 2026.000013', exact: true })
  await expect(details).toContainText('Encaminhamento do lote 13.')
  await details.getByRole('button', { name: 'Fechar diálogo', exact: true }).click()
  await expect(pagination).toContainText('2 / 3')
  await pagination.getByRole('button', { name: 'Próxima', exact: true }).click()
  await expect(pagination).toContainText('3 / 3')
  await expect(rows).toHaveCount(3)
  await expect(rows.last().getByRole('heading', { name: 'Lote 2026.000001', exact: true })).toBeAttached()
  await expect(pagination.getByRole('button', { name: 'Próxima', exact: true })).toBeDisabled()
  await pagination.getByRole('button', { name: 'Anterior', exact: true }).click()
  await expect(pagination).toContainText('2 / 3')
  await expect(rows).toHaveCount(10)
})
