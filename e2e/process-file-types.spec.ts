import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('fluxo-publico:tenant:prefeitura-saomateus-ma:user', 'usr-admin')
    localStorage.setItem('fluxo-publico:tenant:prefeitura-saomateus-ma:unit', 'u-prot')
  })
})

test('Arquivos configura definições com extensões e retenção, sem pedir upload', async ({ page }, testInfo) => {
  await page.goto('/saomateusdomaranhao/tipos-processo')
  await expect(page.getByRole('heading', { name: 'Tipos de processo', exact: true })).toBeVisible({ timeout: 15_000 })
  // This scenario exercises an initially empty definition catalog independently
  // of the populated demonstration fixtures.
  await page.evaluate(() => {
    const key = 'fluxo-publico:tenant:prefeitura-saomateus-ma:database:v1'
    const db = JSON.parse(localStorage.getItem(key)!)
    db.protocolTypes.find((type: { id: string }) => type.id === 'pt-buy').fileTypes = []
    localStorage.setItem(key, JSON.stringify(db))
  })
  await page.reload()
  await page.getByRole('button', { name: '0 tipo(s) de arquivo permitido(s) em Compra de material', exact: true }).click()
  const manager = page.getByRole('dialog', { name: 'Arquivos — Compra de material', exact: true })
  await expect(manager.locator('input[type="file"]')).toHaveCount(0)
  await manager.getByRole('button', { name: 'Novo tipo de arquivo' }).click()
  const editor = page.getByRole('dialog', { name: 'Novo tipo de arquivo', exact: true })
  await editor.getByLabel('Nome *').fill('Comprovante de residência')
  await expect(editor.getByRole('button', { name: 'Salvar', exact: true })).toBeDisabled()
  await editor.getByRole('checkbox', { name: 'PDF', exact: true }).check()
  await editor.getByRole('checkbox', { name: 'DOCX', exact: true }).check()
  await editor.getByRole('combobox', { name: 'Retenção', exact: true }).click()
  await page.getByRole('option', { name: '2 anos', exact: true }).click()
  await editor.getByLabel('Observação').fill('Documento recente para conferência.')
  await editor.screenshot({ path: testInfo.outputPath('file-type-editor.png') })
  await editor.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(manager).toContainText('Comprovante de residência')
  await expect(manager).toContainText('PDF · DOCX · Retenção: 2 anos')
  await manager.getByRole('button', { name: 'Editar Comprovante de residência' }).click()
  const edit = page.getByRole('dialog', { name: 'Editar tipo de arquivo', exact: true })
  await expect(edit.getByLabel('Nome *')).toHaveValue('Comprovante de residência')
  await edit.getByRole('combobox', { name: 'Retenção', exact: true }).click()
  await page.getByRole('option', { name: 'Permanente', exact: true }).click()
  await edit.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(edit).toBeHidden()
  await manager.getByRole('button', { name: 'Fechar', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: '1 tipo(s) de arquivo permitido(s) em Compra de material', exact: true })).toBeVisible()
  await page.goto('/saomateusdomaranhao/processos/pr-1')
  await page.getByRole('button', { name: /^Anexos\b/ }).click()
  const upload = page.locator('input[type="file"][accept=".pdf,.docx"]').last()
  await upload.setInputFiles({ name: 'comprovante.docx', mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', buffer: Buffer.from('Arquivo de teste') })
  const row = page.locator('[data-process-file="attachment"]').filter({ hasText: 'comprovante.docx' })
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: /Visualizar anexo/ }).click()
  const preview = page.getByRole('dialog', { name: 'comprovante.docx', exact: true })
  await expect(preview).toContainText('pré-visualização não está disponível')
  const download = page.waitForEvent('download')
  await preview.getByRole('button', { name: 'Baixar', exact: true }).click()
  expect((await download).suggestedFilename()).toBe('comprovante.docx')
  await preview.getByRole('button', { name: 'Fechar', exact: true }).click()
  await upload.setInputFiles({ name: 'imagem.png', mimeType: 'image/png', buffer: Buffer.from('Arquivo de teste') })
  await expect(page.locator('#main-content').getByRole('alert')).toContainText('não é permitido para este tipo de processo')
  await page.goto('/saomateusdomaranhao/tipos-processo')
  await page.getByRole('button', { name: '1 tipo(s) de arquivo permitido(s) em Compra de material', exact: true }).click()
  await manager.getByRole('button', { name: 'Excluir Comprovante de residência' }).click()
  const remove = page.getByRole('dialog', { name: 'Excluir tipo de arquivo', exact: true })
  await remove.getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(remove).toBeHidden()
  await expect(manager).toContainText('Nenhum tipo de arquivo configurado')
  const retained = await page.evaluate(() => JSON.parse(localStorage.getItem('fluxo-publico:tenant:prefeitura-saomateus-ma:database:v1')!).attachments.some((item: { filename: string }) => item.filename === 'comprovante.docx'))
  expect(retained).toBe(true)
})
