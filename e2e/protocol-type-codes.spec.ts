import { expect, test } from '@playwright/test'

test('cria e edita o código do tipo com prefixo fixo da categoria', async ({ page, isMobile }, testInfo) => {
  await page.addInitScript(() => {
    localStorage.setItem('fluxo-publico:tenant:prefeitura-saomateus-ma:user', 'usr-admin')
    localStorage.setItem('fluxo-publico:tenant:prefeitura-saomateus-ma:unit', 'u-prot')
  })
  await page.goto('/saomateusdomaranhao/tipos-processo')
  await page.getByRole('button', { name: 'Novo', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Novo tipo de processo' })
  const prefix = dialog.locator('[aria-label="Prefixo da categoria"]')
  await expect(prefix).toHaveText('01.')
  await dialog.getByRole('combobox', { name: 'Categoria', exact: true }).click()
  await page.getByRole('option', { name: '02 — Procedimentos Administrativos', exact: true }).click()
  await expect(prefix).toHaveText('02.')
  const suffix = dialog.getByLabel('Código *')
  await suffix.fill('99')
  await expect(dialog.getByRole('button', { name: 'Salvar', exact: true })).toBeDisabled()
  await suffix.fill('999')
  await dialog.getByLabel('Descrição *').fill('Procedimento numerado')
  await dialog.getByLabel('Observação *').fill('Validação do código vinculado à categoria.')
  await suffix.scrollIntoViewIfNeeded()
  const prefixBox = await prefix.boundingBox()
  const codeBox = await suffix.boundingBox()
  expect(Math.abs(prefixBox!.y - codeBox!.y)).toBeLessThan(1)
  expect(Math.abs(prefixBox!.height - codeBox!.height)).toBeLessThan(1)
  const descriptionBox = await dialog.getByLabel('Descrição *').boundingBox()
  if (!isMobile) expect(Math.abs(descriptionBox!.y - codeBox!.y)).toBeLessThan(1)
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await dialog.screenshot({ path: testInfo.outputPath('type-code.png') })
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.getByRole('textbox', { name: 'Buscar tipo de processo' }).fill('02.999')
  await expect(page.getByRole('heading', { name: '02.999 Procedimento numerado' })).toBeVisible()
  await page.getByRole('button', { name: 'Novo', exact: true }).click()
  await dialog.getByLabel('Código *').fill('001')
  await expect(dialog.getByText('Este código já está em uso nesta categoria.')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Salvar', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('button', { name: 'Editar Procedimento numerado', exact: true }).click()
  const edit = page.getByRole('dialog', { name: 'Editar tipo de processo' })
  await expect(edit.getByLabel('Código *')).toHaveValue('999')
  await edit.getByRole('combobox', { name: 'Categoria', exact: true }).click()
  await page.getByRole('option', { name: '01 — Serviço Público', exact: true }).click()
  await expect(edit.locator('[aria-label="Prefixo da categoria"]')).toHaveText('01.')
  await expect(edit.getByLabel('Código *')).toHaveValue('999')
  await edit.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(edit).toBeHidden()
  await page.reload()
  await page.getByRole('textbox', { name: 'Buscar tipo de processo' }).fill('01.999')
  await expect(page.getByRole('heading', { name: '01.999 Procedimento numerado' })).toBeVisible()
})
