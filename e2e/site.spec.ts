import { expect, test } from '@playwright/test'

test('rota raiz apresenta o site e não inicia o ambiente de uma prefeitura', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Gestão em movimento.')
  await expect(page.getByRole('heading', { name: 'Governança', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Compliance', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Integridade', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Explorar demonstração', exact: true }).first()).toHaveAttribute('href', '/saomateusdomaranhao/')
  await expect(page.getByText('Contato de exemplo', { exact: true })).toBeVisible()
  const storage = await page.evaluate(() => Object.keys(localStorage))
  expect(storage.some((key) => key.includes('database:') || key.endsWith(':user'))).toBe(false)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await expect(page).toHaveTitle(/PGCI.*Governança/)
  await page.evaluate(() => document.fonts.ready)
  await page.locator('.site-hero').evaluate((element) => Promise.all(element.getAnimations({ subtree: true }).map((animation) => animation.finished)))
  await page.screenshot({ path: testInfo.outputPath('site-home.png') })
  await page.screenshot({ path: testInfo.outputPath('site-full.png'), fullPage: true })
})

test('recursos podem ser explorados com clique e teclado e FAQ explica a demonstração', async ({ page }) => {
  await page.goto('/#recursos')
  const documents = page.getByRole('tab', { name: 'Documentos e anexos' })
  await documents.click()
  await expect(documents).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tabpanel')).toContainText('O documento acompanha o processo.')
  await documents.press('ArrowDown')
  await expect(page.getByRole('tab', { name: 'Fluxos e checklists' })).toBeFocused()
  await expect(page.getByRole('tabpanel')).toContainText('Cada etapa, com critérios para seguir.')
  await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: 'Ambiente por prefeitura' })).toBeFocused()
  await expect(page.getByRole('tabpanel')).toContainText('Um sistema. A sua forma de trabalhar.')
  await page.getByText('Posso conhecer o sistema antes de utilizar?', { exact: true }).click()
  await expect(page.locator('details[open]')).toContainText('login e a assinatura são simulações')
  const contact = page.getByRole('link', { name: 'comercial@pgci.example', exact: true })
  await expect(contact).toHaveAttribute('href', /^mailto:comercial@pgci\.example\?subject=/)
})

test('seleção de prefeitura filtra resultados e conduz ao login com slug', async ({ page }) => {
  await page.goto('/')
  const access = page.getByRole('button', { name: 'Acessar minha prefeitura', exact: true })
  await access.click()
  let dialog = page.getByRole('dialog', { name: 'Acessar minha prefeitura' })
  await dialog.getByRole('searchbox', { name: 'Buscar prefeitura' }).fill('cidade inexistente')
  await expect(dialog.getByRole('status')).toContainText('Nenhuma prefeitura encontrada')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(access).toBeFocused()
  await access.click()
  dialog = page.getByRole('dialog', { name: 'Acessar minha prefeitura' })
  await dialog.getByRole('searchbox', { name: 'Buscar prefeitura' }).fill('sao mateus')
  await dialog.getByRole('link', { name: /Prefeitura Municipal de São Mateus/ }).click()
  await expect(page).toHaveURL(/\/saomateusdomaranhao\/$/)
  await expect(page.getByRole('heading', { name: 'Acesse sua conta', exact: true })).toBeVisible()
})

test('menu navega por seções e demonstração abre o ambiente correto', async ({ page, isMobile }) => {
  await page.goto('/')
  if (isMobile) await page.getByRole('button', { name: 'Abrir menu do site' }).click()
  await page.getByRole('navigation', { name: 'Navegação do site' }).getByRole('link', { name: 'Como funciona', exact: true }).click()
  await expect(page).toHaveURL(/\/#como-funciona$/)
  if (isMobile) await expect(page.getByRole('button', { name: 'Abrir menu do site' })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('link', { name: 'Explorar demonstração', exact: true }).last().click()
  await expect(page).toHaveURL(/\/saomateusdomaranhao\/$/)
  await expect(page.getByRole('heading', { name: 'Acesse sua conta', exact: true })).toBeVisible()
})
